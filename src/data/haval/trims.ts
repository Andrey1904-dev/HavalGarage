export const trimsForModel = (modelId: string, includeArchive = false): Trim[] =>
  TRIMS.filter((t) => t.modelId === modelId && (includeArchive || t.status === 'current'))

export const getTrim = (id: string): Trim | undefined => TRIMS.find((t) => t.id === id)

/** Минимальная подтверждённая цена текущих комплектаций модели */
export const minCurrentPrice = (modelId: string): Trim | null => {
  const withPrice = trimsForModel(modelId).filter((t) => t.basePrice !== null)
  if (withPrice.length === 0) return null
  return withPrice.reduce((a, b) => ((a.basePrice ?? Infinity) <= (b.basePrice ?? Infinity) ? a : b))
}
